-- =============================================================================
-- Stratos — phase 3: the owner's private document library
--
-- One document system, per project, for paid and Impact projects alike. The
-- Documents screen and the project screen read the same rows and the same
-- stored objects; there is no second copy anywhere.
--
--   1. limits          `document_max_bytes()` — one number, used by the bucket,
--                      the upload start and the completion check
--   2. the bucket      `project-documents`, private, size-limited
--   3. folders         `document_folders`: a tree per project, no cycles, no
--                      parent in another project
--   4. documents       `project_documents`: one row per file; the stored object
--                      lives at `<project id>/<document id>` and nowhere else
--   5. row rules       the upload lifecycle (pending → ready | failed), which is
--                      only allowed to reach `ready` when the stored object is
--                      really there at the declared size
--   6. operations      start an upload, finish it, move, trash, restore — each
--                      a SECURITY INVOKER function, so RLS decides
--   7. maintenance     reconcile stale uploads; report orphans. Report, never
--                      delete.
--   8. access          owner-only on the tables AND on storage.objects, with
--                      restrictive guards so no other storage policy can open
--                      this bucket to anyone else
--
-- WHY THE STORAGE PATH IS TWO IDS
-- -------------------------------
-- A name is something a person changes; an id is not. The object key is
-- `<project_id>/<document_id>`, generated by the database, so renaming a file,
-- renaming a folder or moving a file between folders is an UPDATE of one row
-- and never a copy of bytes. A document cannot move to another project (its
-- project id is fixed), so the key never has to change.
--
-- WHAT THIS DOES NOT DO
-- ---------------------
-- No permanent deletion anywhere: no DELETE grant on either table, no DELETE or
-- UPDATE policy on this bucket's objects, and a restrictive guard that refuses
-- both even if another policy would allow them. "Delete" is the trash, which is
-- reversible — and trashed files STILL OCCUPY STORAGE until someone removes
-- them by hand from the Supabase dashboard (supabase/DOCUMENTS.md §6).
--
-- No client accounts, sharing or client uploads (the next phase). The model
-- leaves room for them — every row is keyed by id and records who uploaded it —
-- without building any of it.
--
-- `media_assets` (20260801000100) is an older, unused scaffold with no bucket
-- and no screen. It is left untouched and is NOT this library.
--
-- Run after the owner lockdown (20260928000300) and the Impact programme
-- (20260929000300). Refuses to run otherwise — see §0.
-- =============================================================================


