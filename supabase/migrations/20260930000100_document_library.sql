-- ------------------------------------------------------------ the tables
-- The owner, and nobody else, for every operation the grants allow. FORCE so
-- the table owner's own sessions are held to it too.
alter table document_folders  enable row level security;
alter table document_folders  force  row level security;
alter table project_documents enable row level security;
alter table project_documents force  row level security;

drop policy if exists document_folders_owner_all  on document_folders;
drop policy if exists project_documents_owner_all on project_documents;
create policy document_folders_owner_all on document_folders
  for all using (is_owner()) with check (is_owner());
create policy project_documents_owner_all on project_documents
  for all using (is_owner()) with check (is_owner());

-- Grants: read, create, change. Never DELETE — for anybody, the owner
-- included: there is no hard-delete path through the API. anon gets nothing.
do $$
declare
  f text;
begin
  execute 'revoke all on table document_folders, project_documents from public';
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on table document_folders, project_documents from anon';
  end if;
  if exists (select 1 from pg_roles where rolname = 'authenticated') then
    execute 'revoke all on table document_folders, project_documents from authenticated';
    execute 'grant select, insert, update on table document_folders, project_documents to authenticated';
  end if;

  -- The functions: the owner's operations for `authenticated` (each answers to
  -- RLS, so a non-owner gets nothing done); nothing for anon.
  foreach f in array array[
    'document_object_size(text)',
    'document_lock(uuid)',
    'document_free_name(uuid, uuid, text, uuid, text)',
    'document_begin_upload(uuid, uuid, text, bigint, text, text)',
    'document_finish_upload(uuid)',
    'document_move(uuid, uuid)',
    'document_restore_folder_chain(uuid)',
    'document_restore(uuid)',
    'document_trash_folder(uuid)',
    'document_restore_folder(uuid)',
    'document_reconcile()',
    'document_storage_report()'
  ] loop
    execute format('revoke all on function %s from public', f);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on function %s from anon', f);
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
      execute format('grant execute on function %s to authenticated', f);
    end if;
  end loop;
end $$;

-- ------------------------------------------------------------ the objects
-- Storage checks these policies with the caller's own JWT (`authenticated` +
-- `request.jwt.claims`), which is why `is_owner()` works here unchanged.
--
-- PERMISSIVE — what the owner may do in this bucket:
--   select   every object (signed download URLs, downloads, the report)
--   insert   ONLY at the path of a live `pending` document row. Creating a
--            signed upload URL runs this check, so each URL is for exactly one
--            document's path, and only while that row is waiting for its file.
-- There is no permissive UPDATE (so no upsert / overwrite) and no DELETE.
--
-- RESTRICTIVE — guards ANDed with every other policy on storage.objects, so a
-- broad policy written for some other bucket (or later, by hand) can never
-- open this one: in this bucket, select needs the owner, insert needs the owner
-- and a pending row, and update and delete are refused outright.
drop policy if exists project_documents_owner_select on storage.objects;
drop policy if exists project_documents_owner_insert on storage.objects;
drop policy if exists project_documents_guard_select on storage.objects;
drop policy if exists project_documents_guard_insert on storage.objects;
drop policy if exists project_documents_guard_update on storage.objects;
drop policy if exists project_documents_guard_delete on storage.objects;
-- Left by supabase/checks/documents-rollback.sql; re-applying this file lifts it.
drop policy if exists project_documents_sealed on storage.objects;

create policy project_documents_owner_select on storage.objects
  as permissive for select to authenticated
  using (bucket_id = 'project-documents' and public.is_owner());

create policy project_documents_owner_insert on storage.objects
  as permissive for insert to authenticated
  with check (
    bucket_id = 'project-documents'
    and public.is_owner()
    and exists (select 1 from public.project_documents d
                where d.storage_path = objects.name and d.upload_state = 'pending' and d.trashed_at is null)
  );

create policy project_documents_guard_select on storage.objects
  as restrictive for select
  using (bucket_id <> 'project-documents' or public.is_owner());

create policy project_documents_guard_insert on storage.objects
  as restrictive for insert
  with check (
    bucket_id <> 'project-documents'
    or (public.is_owner()
        and exists (select 1 from public.project_documents d
                    where d.storage_path = objects.name and d.upload_state = 'pending' and d.trashed_at is null))
  );

create policy project_documents_guard_update on storage.objects
  as restrictive for update
  using (bucket_id <> 'project-documents')
  with check (bucket_id <> 'project-documents');

create policy project_documents_guard_delete on storage.objects
  as restrictive for delete
  using (bucket_id <> 'project-documents');

-- ------------------------------------------------ no overwrite, by any path
-- The policies above cannot stop an overwrite on their own. Observed on a real
-- local Supabase (Storage 1.77, scripts/documents-live-check.mjs):
--   * `createSignedUploadUrl(path, { upsert: true })` IS issued for a pending
--     path — Storage checks only the INSERT policy when the link is made;
--   * the upload with that token runs as Storage's superuser, so no policy is
--     consulted, and with upsert it UPDATES the existing row — after the
--     document was finished, "hello" was replaced by other bytes.
-- So the rule is enforced below RLS: in this bucket a stored object's row can
-- never be updated. Storage writes the new bytes under a fresh version first
-- and deletes them when its database step fails, so the refused overwrite
-- leaves the original object and its bytes untouched (observed: the second PUT
-- answers 400 and the download still returns the original).
-- Nothing in the library ever needs to update an object: keys are generated,
-- there is no move, rename or replace of a stored file.
create or replace function document_object_immutable() returns trigger
  language plpgsql
  set search_path = public
as $$
begin
  if old.bucket_id = 'project-documents' or new.bucket_id = 'project-documents' then
    raise exception 'stratos:document_object_immutable'
      using errcode = '42501',
            hint = 'A stored document is never overwritten. Upload a new file instead.';
  end if;
  return new;
end;
$$;

drop trigger if exists project_documents_no_overwrite on storage.objects;
create trigger project_documents_no_overwrite
  before update on storage.objects
  for each row execute function document_object_immutable();
